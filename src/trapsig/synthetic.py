"""SYNTHETIC demonstration data. Not a measurement of any experiment.

Generates small CSV recordings with known blockade events so that every stage
of the pipeline can be exercised end-to-end before real data are available.
Every file carries a ``SYNTHETIC`` header line; the metadata CSV links each file
to a class, replicate, and session so that grouping logic is exercised too.

The event parameters below are invented for testing only. They must never be
used as evidence about any physical system.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np

SYNTHETIC_BANNER = "# SYNTHETIC DATA - NOT A MEASUREMENT - generated by trapsig.synthetic"

# Invented class parameters (testing only): (depth as fraction of baseline, duration in s)
CLASS_PARAMS: dict[str, tuple[float, float]] = {
    "A": (0.12, 0.010),
    "B": (0.30, 0.040),
}


@dataclass(frozen=True)
class SyntheticSpec:
    fs_hz: float = 100_000.0
    duration_s: float = 0.5
    baseline_a: float = 1.0e-10
    noise_sd_a: float = 3.0e-12
    mains_amp_a: float = 1.0e-12
    replicates_per_class: int = 6
    files_per_replicate: int = 1
    seed: int = 0
    file_format: str = "csv"   # "csv" (with banner) or "dat" (raw float32 little-endian)


def _simulate_recording(
    rng: np.random.Generator, spec: SyntheticSpec, cls: str
) -> tuple[np.ndarray, list[tuple[float, float, float]]]:
    """Return the trace and the injected truth as ``(onset_s, duration_s, depth)`` tuples."""
    n = int(round(spec.fs_hz * spec.duration_s))
    t = np.arange(n) / spec.fs_hz
    current = np.full(n, spec.baseline_a)
    current += spec.noise_sd_a * rng.standard_normal(n)
    current += spec.mains_amp_a * np.sin(2 * np.pi * 50.0 * t)           # mains hum
    current += 0.5 * spec.mains_amp_a * np.sin(2 * np.pi * 0.2 * t + 1.0)  # slow drift
    depth, dur = CLASS_PARAMS[cls]
    n_events = int(rng.integers(1, 4))
    width = int(round(dur * spec.fs_hz))
    truth: list[tuple[float, float, float]] = []
    for _ in range(n_events):
        start = int(rng.integers(0, max(1, n - width)))
        current[start:start + width] *= (1.0 - depth)
        truth.append((start / spec.fs_hz, width / spec.fs_hz, depth))
    return current, truth


def write_synthetic_dataset(
    root: str | Path,
    spec: SyntheticSpec | None = None,
    classes: tuple[str, ...] = ("A", "B"),
    *,
    class_folders: bool = False,
) -> Path:
    """Write recordings under ``root``, plus metadata and ground-truth CSVs beside it.

    Returns the metadata CSV path. The truth file is ``<root>_truth.csv`` and is
    used only to validate detection; the pipeline never reads it. Existing files
    are not overwritten.
    """
    spec = spec or SyntheticSpec()
    if spec.file_format not in ("csv", "dat"):
        raise ValueError(f"file_format must be 'csv' or 'dat', not {spec.file_format!r}")
    root = Path(root)
    root.mkdir(parents=True, exist_ok=True)
    ext = spec.file_format
    if ext == "dat":
        notice = root / "SYNTHETIC_NOTICE.txt"
        if notice.exists():
            raise FileExistsError(f"refusing to overwrite {notice}")
        notice.write_text(SYNTHETIC_BANNER + "\n"
                          "Binary .dat files cannot carry this banner inside the file.\n", encoding="utf-8")
    meta_path = root.parent / f"{root.name}_metadata.csv"
    truth_path = root.parent / f"{root.name}_truth.csv"
    if meta_path.exists() or truth_path.exists():
        raise FileExistsError(f"refusing to overwrite {meta_path} or {truth_path}")
    rng = np.random.default_rng(spec.seed)
    lines = ["file,class,replicate_id,session_id"]
    truth_lines = ["file,class,onset_s,duration_s,depth"]
    for cls in classes:
        for rep in range(spec.replicates_per_class):
            session = f"S{rep % 2 + 1}"
            for k in range(spec.files_per_replicate):
                name = f"SYN_{cls}_R{rep:02d}_F{k}.{ext}"
                x, truth = _simulate_recording(rng, spec, cls)
                for onset, dur, depth in truth:
                    truth_lines.append(f"{name},{cls},{onset:.6f},{dur:.6f},{depth:.4f}")
                folder = root / cls if class_folders else root
                folder.mkdir(parents=True, exist_ok=True)
                path = folder / name
                if path.exists():
                    raise FileExistsError(f"refusing to overwrite {path}")
                if ext == "csv":
                    with path.open("x", encoding="utf-8") as fh:
                        fh.write(SYNTHETIC_BANNER + "\n")
                        fh.write(f"# sampling_rate_hz: {spec.fs_hz:g}\n")
                        fh.write("# units: A\n")
                        np.savetxt(fh, x, fmt="%.6e")
                else:
                    with path.open("xb") as fh:
                        fh.write(x.astype("<f4").tobytes())
                lines.append(f"{name},{cls},R{rep:02d},{session}")
    with meta_path.open("x", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    with truth_path.open("x", encoding="utf-8") as fh:
        fh.write("\n".join(truth_lines) + "\n")
    return meta_path
